const MINOR_ARCANA = [...WANDS_CARDS, ...CUPS_CARDS, ...SWORDS_CARDS, ...PENTACLES_CARDS];

if (MINOR_ARCANA.length !== 56) console.warn('Expected 56 minor cards, got ' + MINOR_ARCANA.length);

// ── Utility helpers ────────────────────────────────────
function getMinorCardById(id) {
  return MINOR_ARCANA.find(c => c.id === id);
}

function getCardsBySuit(suit) {
  return MINOR_ARCANA.filter(c => c.suit === suit);
}

function getMinorCardsBySuitAndRank(suit, rank) {
  return MINOR_ARCANA.find(c => c.suit === suit && c.rank === rank);
}
